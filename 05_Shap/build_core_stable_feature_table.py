def direction_labels(task: str, positive_fraction: float, consistency: float) -> Tuple[str, str, str]:
    meta = TASK_META.get(task, TASK_META["LOI"])
    if not np.isfinite(positive_fraction) or not np.isfinite(consistency):
        return "Unknown", "方向信息不足", "需补充样本级SHAP"

    if consistency >= 0.8 and positive_fraction >= 0.8:
        output_direction = "Predominantly positive"
        output_cn = meta["positive_output_cn"]
        favorable = meta["objective"] == "max"
    elif consistency >= 0.8 and positive_fraction <= 0.2:
        output_direction = "Predominantly negative"
        output_cn = meta["negative_output_cn"]
        favorable = meta["objective"] == "min"
    else:
        return (
            "Mixed/unstable",
            "不同外层折或子特征的平均SHAP方向不完全一致",
            "不能判断有利/不利；必须结合样本级SHAP依赖图",
        )

    performance_cn = "总体方向与目标优化方向一致" if favorable else "总体方向与目标优化方向相反"
    return output_direction, output_cn, performance_cn


def weighted_average(values: pd.Series, weights: pd.Series) -> float:
    v = pd.to_numeric(values, errors="coerce").to_numpy(dtype=float)
    w = pd.to_numeric(weights, errors="coerce").fillna(0).to_numpy(dtype=float)
    mask = np.isfinite(v) & np.isfinite(w)
    if not mask.any():
        return float("nan")
    if np.sum(w[mask]) <= 0:
        return float(np.nanmean(v[mask]))
    return float(np.average(v[mask], weights=w[mask]))


def find_input_csv(figures_dir: Path, results_root: Path, task: str) -> Path:
    candidates = [
        figures_dir / f"{task}_SHAP_stable_features_filtered.csv",
        results_root / "figures" / f"{task}_SHAP_stable_features_filtered.csv",
    ]
    for p in candidates:
        if p.exists():
            return p
    matches = list(results_root.rglob(f"{task}_SHAP_stability_summary.csv"))
    if len(matches) == 1:
        return matches[0]
    if not matches:
        raise FileNotFoundError(f"No stable SHAP table found for {task} under {results_root}")
    raise RuntimeError(f"Multiple SHAP stability tables found for {task}: {matches}")


def read_task_table(path: Path, task: str, include_levels: Iterable[str]) -> pd.DataFrame:
    df = pd.read_csv(path)
    required = {
        "feature",
        "feature_group",
        "mean_abs_shap_all_folds",
        "selected_feature_frequency",
        "top20_frequency",
        "direction_consistency",
        "positive_direction_fraction_when_selected",
        "folds_present",
        "n_shap_folds",
    }
    missing = required.difference(df.columns)
    if missing:
        raise ValueError(f"{path} is missing columns: {sorted(missing)}")
    if "stability_level" not in df.columns:
        def infer_level(row: pd.Series) -> str:
            if (
                row.get("folds_present", 0) >= row.get("n_shap_folds", 5)
                and row.get("selected_feature_frequency", 0) >= 0.8
                and row.get("top20_frequency", 0) >= 0.8
                and row.get("direction_consistency", 0) >= 0.8
            ):
                return "High"
            if (
                row.get("folds_present", 0) >= 4
                and row.get("selected_feature_frequency", 0) >= 0.8
                and row.get("top20_frequency", 0) >= 0.6
                and row.get("direction_consistency", 0) >= 0.6
            ):
                return "Medium"
            return "Low"
        df["stability_level"] = df.apply(infer_level, axis=1)

    include = {x.strip() for x in include_levels if x.strip()}
    df = df[df["stability_level"].astype(str).isin(include)].copy()
    df.insert(0, "task", task)
    df["source_csv"] = str(path)
    return df


def build_child_table(task_tables: List[pd.DataFrame]) -> pd.DataFrame:
    child = pd.concat(task_tables, ignore_index=True)
    maps = child.apply(
        lambda r: pd.Series(map_feature_to_parent(str(r["feature"]), str(r["feature_group"]))), axis=1
    )
    for col in maps.columns:
        child[col] = maps[col]
    child["child_importance_rank"] = child.groupby("task")["mean_abs_shap_all_folds"].rank(
        method="dense", ascending=False
    ).astype(int)
    return child


def build_parent_table(child: pd.DataFrame) -> pd.DataFrame:
    rows: List[Dict[str, object]] = []
    group_cols = ["task", "parent_variable", "parent_variable_cn", "parent_feature_group", "mechanism_key"]
    for keys, g in child.groupby(group_cols, dropna=False, sort=False):
        task, parent, parent_cn, parent_group, key = keys
        weights = pd.to_numeric(g["mean_abs_shap_all_folds"], errors="coerce").fillna(0)
        stable_levels = sorted(set(g["stability_level"].astype(str)), key=lambda x: -STABLE_LEVEL_ORDER.get(x, 0))
        parent_level = stable_levels[0] if stable_levels else "Low"
        dominant_idx = pd.to_numeric(g["mean_abs_shap_all_folds"], errors="coerce").idxmax()
        dominant_feature = str(g.loc[dominant_idx, "feature"])
        physical, mechanism, caution, literature = mechanism_text(str(key), str(parent_cn))
        pos_frac = weighted_average(g["positive_direction_fraction_when_selected"], weights)
        dir_cons = weighted_average(g["direction_consistency"], weights)
        direction_en, direction_cn, performance_cn = direction_labels(str(task), pos_frac, dir_cons)
        rows.append(
            {
                "task": task,
                "target_cn": TASK_META.get(str(task), {}).get("target_cn", str(task)),
                "parent_variable": parent,
                "parent_variable_cn": parent_cn,
                "parent_feature_group": parent_group,
                "mechanism_key": key,
                "parent_stability_level": parent_level,
                "child_feature_count": int(len(g)),
                "child_features": "; ".join(g.sort_values("mean_abs_shap_all_folds", ascending=False)["feature"].astype(str)),
                "dominant_child_feature": dominant_feature,
                "parent_importance_sum": float(weights.sum()),
                "parent_importance_max_child": float(weights.max()),
                "parent_importance_mean_child": float(weights.mean()),
                "selected_feature_frequency_weighted": weighted_average(g["selected_feature_frequency"], weights),
                "top20_frequency_weighted": weighted_average(g["top20_frequency"], weights),
                "direction_consistency_weighted": dir_cons,
                "positive_direction_fraction_weighted": pos_frac,
                "folds_present_max": int(pd.to_numeric(g["folds_present"], errors="coerce").max()),
                "n_shap_folds_max": int(pd.to_numeric(g["n_shap_folds"], errors="coerce").max()),
                "average_output_direction": direction_en,
                "average_output_direction_cn": direction_cn,
                "performance_direction_cn": performance_cn,
                "physical_meaning_cn": physical,
                "mechanism_interpretation_cn": mechanism,
                "writing_caution_cn": caution,
                "literature_support_needed_cn": literature,
                "aggregation_caution": "Correlated transforms can split SHAP attribution. Use max-child importance for conservative ranking; sum is bookkeeping only.",
            }
        )
    parent = pd.DataFrame(rows)
    parent["parent_importance_share_of_stable_sum"] = parent.groupby("task")["parent_importance_sum"].transform(
        lambda x: x / x.sum() if x.sum() else np.nan
    )
    parent["parent_rank_conservative"] = parent.groupby("task")["parent_importance_max_child"].rank(
        method="dense", ascending=False
    ).astype(int)
    parent["parent_rank_sum"] = parent.groupby("task")["parent_importance_sum"].rank(
        method="dense", ascending=False
    ).astype(int)
    return parent.sort_values(["task", "parent_rank_conservative", "parent_rank_sum", "parent_variable"])


def plot_parent_top(parent_task: pd.DataFrame, task: str, out_dir: Path, top_n: int) -> Tuple[Path, Path]:
    plot_df = parent_task.sort_values(
        ["parent_importance_max_child", "parent_importance_sum"], ascending=False
    ).head(top_n).copy()
    plot_df = plot_df.sort_values("parent_importance_max_child", ascending=True)
    labels = plot_df["parent_variable"].astype(str)
    values = plot_df["parent_importance_max_child"].astype(float)

    height = max(5.5, 0.48 * len(plot_df) + 1.8)
    fig, ax = plt.subplots(figsize=(10.5, height))
    ax.barh(labels, values)
    ax.set_xlabel("Conservative parent importance (max child mean |SHAP|)")
    ax.set_ylabel("")
    ax.set_title(f"{task}: stable SHAP parent variables")
    ax.grid(axis="x", alpha=0.25)
    for idx, (_, row) in enumerate(plot_df.iterrows()):
        ax.text(
            float(row["parent_importance_max_child"]),
            idx,
            f"  n={int(row['child_feature_count'])}; {row['parent_stability_level']}",
            va="center",
            fontsize=8.5,
        )
    fig.tight_layout()
    png = out_dir / f"{task}_SHAP_parent_top{top_n}.png"
    pdf = out_dir / f"{task}_SHAP_parent_top{top_n}.pdf"
    fig.savefig(png, dpi=600, bbox_inches="tight")
    fig.savefig(pdf, bbox_inches="tight")
    plt.close(fig)
    return png, pdf


def write_markdown_summary(
    parent: pd.DataFrame,
    output_path: Path,
    top_n: int,
    tasks: Iterable[str] | None = None,
    title: str = "核心任务SHAP稳定父变量汇总",
) -> None:
    lines: List[str] = []
    lines.append(f"# {title}")
    lines.append("")
    lines.append("> 说明：父变量按其最重要子特征的mean |SHAP|进行保守排序。SHAP反映模型依赖关系，不代表因果关系；数学变换项的贡献可能因共线性被拆分。")
    lines.append("")
    task_order = list(tasks) if tasks is not None else list(dict.fromkeys(parent["task"].astype(str)))
    for task in task_order:
        g = parent[parent["task"] == task].sort_values("parent_rank_conservative").head(top_n)
        if g.empty:
            continue
        lines.append(f"## {task}")
        lines.append("")
        lines.append("| 排名 | 父变量 | 稳定级别 | 保守重要性 | 子特征数 | 平均方向 | 论文解释重点 |")
        lines.append("|---:|---|---|---:|---:|---|---|")
        for _, r in g.iterrows():
            mechanism = str(r["mechanism_interpretation_cn"]).replace("|", "；")
            if len(mechanism) > 88:
                mechanism = mechanism[:88] + "……"
            lines.append(
                f"| {int(r['parent_rank_conservative'])} | {r['parent_variable_cn']} | {r['parent_stability_level']} | "
                f"{float(r['parent_importance_max_child']):.6g} | {int(r['child_feature_count'])} | "
                f"{r['average_output_direction_cn']} | {mechanism} |"
            )
        lines.append("")
        lines.append("**写作提醒：** 只有方向一致性较高且正/负方向占比明确时，才能描述为“总体偏正/偏负”；判断单调关系仍需样本级SHAP依赖图。")
        lines.append("")
    output_path.write_text("\n".join(lines), encoding="utf-8")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Merge stable SHAP child features into parent variables.")
    parser.add_argument("--results-root", default="results/05_Shap/FINAL_core_fixed_baseline_inclusive_5x5", help="Root containing core SHAP task results.")
    parser.add_argument("--figures-dir", default="results/05_Shap/FINAL_core_fixed_baseline_inclusive_5x5/figures", help="Folder with *_stable_features_filtered.csv files.")
    parser.add_argument("--output-dir", default="results/05_Shap/core_features", help="Canonical output folder.")
    parser.add_argument("--tasks", default=",".join(DEFAULT_TASKS), help="Comma-separated tasks.")
    parser.add_argument("--include-levels", default="High,Medium", help="Stability levels to aggregate.")
