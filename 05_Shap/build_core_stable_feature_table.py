def main() -> int:
    args = parse_args()
    tasks = [x.strip() for x in args.tasks.split(",") if x.strip()]
    levels = [x.strip() for x in args.include_levels.split(",") if x.strip()]
    results_root = Path(args.results_root).resolve()
    figures_dir = Path(args.figures_dir).resolve()
    output_dir = Path(args.output_dir).resolve()
    tables_dir = output_dir / "tables"
    figures_out = output_dir / "figures"
    tables_dir.mkdir(parents=True, exist_ok=True)
    figures_out.mkdir(parents=True, exist_ok=True)

    task_tables: List[pd.DataFrame] = []
    manifest_rows: List[Dict[str, object]] = []
    for task in tasks:
        print("=" * 88)
        print(f"[STEP2] task={task}")
        source = find_input_csv(figures_dir, results_root, task)
        df = read_task_table(source, task, levels)
        task_tables.append(df)
        manifest_rows.append({"task": task, "source_csv": str(source), "stable_child_features": len(df)})
        print(f"[OK] {task}: source={source}; selected stable child features={len(df)}")

    child = build_child_table(task_tables)
    parent = build_parent_table(child)

    prefix = str(args.output_prefix).strip() or "core"
    step_label = str(args.step_label).strip() or "STEP2"
    child_path = tables_dir / f"{prefix}_stable_child_features_with_parent_mapping.csv"
    parent_path = tables_dir / f"{prefix}_stable_parent_variables.csv"
    mechanism_path = tables_dir / f"{prefix}_parent_variable_mechanism_template.csv"
    audit_path = tables_dir / f"{prefix}_parent_feature_mapping_audit.csv"

    child.to_csv(child_path, index=False, encoding="utf-8-sig")
    parent.to_csv(parent_path, index=False, encoding="utf-8-sig")
    parent[[
        "task", "parent_rank_conservative", "parent_variable", "parent_variable_cn",
        "parent_feature_group", "parent_stability_level", "average_output_direction_cn",
        "performance_direction_cn", "physical_meaning_cn", "mechanism_interpretation_cn",
        "writing_caution_cn", "literature_support_needed_cn", "child_features"
    ]].to_csv(mechanism_path, index=False, encoding="utf-8-sig")
    child[[
        "task", "feature", "feature_group", "stability_level", "parent_variable",
        "parent_variable_cn", "parent_feature_group", "mapping_type", "transform_tags",
        "mechanism_key", "mapping_note"
    ]].to_csv(audit_path, index=False, encoding="utf-8-sig")

    plot_manifest: List[Dict[str, object]] = []
    for task in tasks:
        g = parent[parent["task"] == task].copy()
        task_table = tables_dir / f"{task}_stable_parent_variables.csv"
        g.to_csv(task_table, index=False, encoding="utf-8-sig")
        png, pdf = plot_parent_top(g, task, figures_out, args.top_parent_n)
        plot_manifest.append({
            "task": task,
            "parent_variables": len(g),
            "top_plot_png": str(png),
            "top_plot_pdf": str(pdf),
            "task_table": str(task_table),
        })
        print(f"[OK] {task}: parent variables={len(g)}; plot={png.name}")

    summary_path = output_dir / f"{step_label}_{prefix}_parent_variable_summary.md"
    write_markdown_summary(
        parent, summary_path, args.top_parent_n, tasks=tasks, title=args.summary_title
    )

    manifest = pd.DataFrame(manifest_rows).merge(pd.DataFrame(plot_manifest), on="task", how="left")
    manifest_path = output_dir / f"{step_label}_manifest.csv"
    manifest.to_csv(manifest_path, index=False, encoding="utf-8-sig")

    config = {
        "tasks": tasks,
        "include_levels": levels,
        "ranking_rule": "parent_importance_max_child descending (conservative)",
        "sum_importance_note": "parent_importance_sum is bookkeeping because correlated transforms can split SHAP attribution",
        "direction_note": "average SHAP-output direction only; not proof of monotonicity or causality",
        "top_parent_n": args.top_parent_n,
        "output_prefix": prefix,
        "step_label": step_label,
        "summary_title": args.summary_title,
        "results_root": str(results_root),
        "figures_dir": str(figures_dir),
        "output_dir": str(output_dir),
    }
    (output_dir / f"{step_label}_run_config.json").write_text(json.dumps(config, ensure_ascii=False, indent=2), encoding="utf-8")

    print("\n[DONE] Parent table:", parent_path)
    print("[DONE] Mechanism template:", mechanism_path)
    print("[DONE] Summary:", summary_path)
    print("[DONE] Manifest:", manifest_path)
    return 0


