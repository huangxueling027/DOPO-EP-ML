def _clean_text(value: object) -> str:
    return "" if pd.isna(value) else str(value).strip()


def _strip_transform_suffixes(feature: str) -> Tuple[str, List[str]]:
    """Remove repeated mathematical transform suffixes and return audit tags."""
    s = feature.strip()
    transforms: List[str] = []
    suffixes = [
        (r"_sqrt$", "sqrt"),
        (r"_sq$", "square"),
        (r"_log1p$", "log1p"),
        (r"_log$", "log"),
        (r"_cube$", "cube"),
        (r"_abs$", "absolute"),
    ]
    changed = True
    while changed:
        changed = False
        for pattern, label in suffixes:
            if re.search(pattern, s, flags=re.I):
                s = re.sub(pattern, "", s, flags=re.I)
                transforms.append(label)
                changed = True
                break
    return s, transforms


def _normalize_base_token(token: str) -> str:
    s = token.strip()
    s = re.sub(r"\s*wt%$", "", s, flags=re.I)
    s = s.replace("_wt%", "")
    s = re.sub(r"__+", "_", s)
    return s.strip("_")


def _descriptor_label(desc: str) -> Tuple[str, str]:
    desc = desc.strip("_")
    cn = DESCRIPTOR_CN.get(desc, desc)
    return desc, cn


def _target_display(token: str) -> str:
    key = token.strip().lower()
    return {
        "loi": "LOI",
        "phrr": "PHRR",
        "thr": "THR",
        "tg": "Tg",
        "ts": "TS",
        "ts_mpa": "TS",
    }.get(key, token)


def map_feature_to_parent(feature: str, feature_group: str) -> Dict[str, str]:
    """Map one engineered feature to a parent variable and interpretation key."""
    raw = feature.strip()
    base, transforms = _strip_transform_suffixes(raw)
    base_norm = _normalize_base_token(base)
    transform_text = ",".join(transforms) if transforms else "none"

    result = {
        "parent_variable": base_norm,
        "parent_variable_cn": base_norm,
        "parent_feature_group": feature_group,
        "mapping_type": "direct",
        "transform_tags": transform_text,
        "mechanism_key": "other",
        "mapping_note": "Direct mapping; review manually if used in the manuscript.",
    }

    # Fingerprints: keep each bit separate until RDKit substructure mapping is done.
    m = re.match(r"^(main|co|curing)_(morgan_r\d+|maccs)_(\d+)$", base_norm, flags=re.I)
    if m:
        scope, fp_type, bit = m.groups()
        scope_en = {"main": "Main FR", "co": "Co-FR", "curing": "Curing agent"}[scope.lower()]
        scope_cn = {"main": "主阻燃剂", "co": "协同阻燃剂", "curing": "固化剂"}[scope.lower()]
        result.update(
            parent_variable=f"{scope_en} {fp_type.upper()} bit {bit}",
            parent_variable_cn=f"{scope_cn}{fp_type.upper()}指纹位{bit}",
            parent_feature_group="molecular_fingerprint",
            mapping_type="fingerprint_bit",
            mechanism_key="fingerprint",
            mapping_note="Fingerprint bit retained separately; map the bit back to a chemical substructure before mechanistic interpretation.",
        )
        return result

    # Main interaction forms.
    m = re.match(r"^Synergy_x_EP_matrix_(LOI|PHRR|THR|Tg|TS(?:_MPa)?)$", base_norm, flags=re.I)
    if m:
        target = _target_display(m.group(1))
        result.update(
            parent_variable=f"Synergy × EP matrix {target}",
            parent_variable_cn=f"协同状态×未改性EP的{target}",
            parent_feature_group="formulation_interaction",
            mapping_type="interaction",
            mechanism_key="synergy_ep_baseline",
            mapping_note="Interaction feature; do not merge with the EP baseline main effect.",
        )
        return result

    m = re.match(r"^P_content_x_EP_matrix_(LOI|PHRR|THR|Tg|TS(?:_MPa)?)$", base_norm, flags=re.I)
    if m:
        target = _target_display(m.group(1))
        result.update(
            parent_variable=f"P content × EP matrix {target}",
            parent_variable_cn=f"磷含量×未改性EP的{target}",
            parent_feature_group="formulation_interaction",
            mapping_type="interaction",
            mechanism_key="p_ep_baseline",
            mapping_note="Interaction feature; represents matrix-dependent phosphorus contribution.",
        )
        return result

    m = re.match(r"^Loading_x_EP_matrix_(LOI|PHRR|THR|Tg|TS(?:_MPa)?)$", base_norm, flags=re.I)
    if m:
        target = _target_display(m.group(1))
        result.update(
            parent_variable=f"FR loading × EP matrix {target}",
            parent_variable_cn=f"阻燃剂添加量×未改性EP的{target}",
            parent_feature_group="formulation_interaction",
            mapping_type="interaction",
            mechanism_key="loading_ep_baseline",
            mapping_note="Interaction feature; represents matrix-dependent loading effect.",
        )
        return result

    m = re.match(r"^P_x_curing_(.+)$", base_norm, flags=re.I)
    if m:
        desc, desc_cn = _descriptor_label(m.group(1))
        result.update(
            parent_variable=f"P content × curing-agent {desc}",
            parent_variable_cn=f"磷含量×固化剂{desc_cn}",
            parent_feature_group="molecular_interaction",
            mapping_type="interaction",
            mechanism_key=f"p_curing_{desc.lower()}",
            mapping_note="Interaction feature coupling phosphorus loading/composition with curing-agent structure.",
        )
        return result

    m = re.match(r"^P_x_CuringAgent_Has_([A-Za-z]+)$", base_norm, flags=re.I)
    if m:
        element = m.group(1).upper()
        result.update(
            parent_variable=f"P content × curing-agent {element} presence",
            parent_variable_cn=f"磷含量×固化剂含{element}",
            parent_feature_group="molecular_interaction",
            mapping_type="interaction",
            mechanism_key="p_curing_element",
            mapping_note="Interaction feature coupling phosphorus with the elemental character of the curing agent.",
        )
        return result

    if re.match(r"^P_loading_x_Synergy$", base_norm, flags=re.I):
        result.update(
            parent_variable="(FR loading × P content) × synergy",
            parent_variable_cn="（阻燃剂添加量×磷含量）×协同状态",
            parent_feature_group="formulation_interaction",
            mapping_type="interaction",
            mechanism_key="p_loading_synergy",
            mapping_note="Legacy-named interaction between total FR loading, formulation-level P content, and synergistic status.",
        )
        return result

    if re.match(r"^Loading_x_Synergy$", base_norm, flags=re.I):
        result.update(
            parent_variable="Total FR loading × synergy",
            parent_variable_cn="总阻燃剂添加量×协同状态",
            parent_feature_group="formulation_interaction",
            mapping_type="interaction",
            mechanism_key="loading_synergy",
            mapping_note="Interaction between total loading and synergistic formulation status.",
        )
        return result

    m = re.match(r"^P_([NBSi]+)_loading_(product|sum|ratio)$", base_norm, flags=re.I)
    if m:
        partner, mode = m.groups()
        partner = partner.replace("SI", "Si").replace("si", "Si")
        result.update(
            parent_variable=f"P–{partner} loading–composition interaction",
            parent_variable_cn=f"P–{partner}添加量–组成交互",
            parent_feature_group="formulation_interaction",
            mapping_type=f"interaction_{mode.lower()}",
            mechanism_key=f"p_{partner.lower()}_loading",
            mapping_note=f"{mode.lower()}-type engineered interaction built from legacy loading×composition features; it is not a direct elemental-loading measurement.",
        )
        return result

    # Baseline property and transforms.
    m = re.match(r"^EP_matrix_(LOI|PHRR|THR|Tg|TS(?:_MPa)?|FS(?:_MPa)?|Char(?:_yield)?)$", base_norm, flags=re.I)
    if m:
        target = m.group(1)
        result.update(
            parent_variable=f"EP matrix {target}",
            parent_variable_cn=f"未改性EP的{target}基线",
            parent_feature_group="ep_baseline",
            mapping_type="base_or_transform",
            mechanism_key="ep_baseline",
            mapping_note="Base and mathematical transforms merged; baseline effect is not a flame-retardant molecular mechanism.",
        )
        return result

    # Core formulation variables.
    exact_map = {
        "Loading_total_FR": ("Total FR loading", "总阻燃剂添加量", "formulation_loading", "fr_loading"),
        "P_content": ("P content", "磷含量", "elemental_composition", "p_content"),
        "N_content": ("N content", "氮含量", "elemental_composition", "n_content"),
        "S_content": ("S content", "硫含量", "elemental_composition", "s_content"),
        "B_content": ("B content", "硼含量", "elemental_composition", "b_content"),
        "Si_content": ("Si content", "硅含量", "elemental_composition", "si_content"),
        "P_loading_real": ("FR loading × P-content interaction", "阻燃剂添加量×磷含量交互", "formulation_interaction", "loading_x_p_content"),
        "N_loading_real": ("FR loading × N-content interaction", "阻燃剂添加量×氮含量交互", "formulation_interaction", "loading_x_n_content"),
        "S_loading_real": ("FR loading × S-content interaction", "阻燃剂添加量×硫含量交互", "formulation_interaction", "loading_x_s_content"),
        "B_loading_real": ("FR loading × B-content interaction", "阻燃剂添加量×硼含量交互", "formulation_interaction", "loading_x_b_content"),
        "Si_loading_real": ("FR loading × Si-content interaction", "阻燃剂添加量×硅含量交互", "formulation_interaction", "loading_x_si_content"),
        "Main_FR_fraction": ("Main FR fraction", "主阻燃剂质量分数", "formulation_loading", "main_fraction"),
        "Co_FR_fraction": ("Co-FR fraction", "协同阻燃剂质量分数", "formulation_loading", "co_fraction"),
        "Cure_Temp_Max": ("Maximum cure temperature", "最高固化温度", "curing_and_preparation", "cure_temperature"),
        "Preparation_Method_num": ("Preparation method", "制备/引入方式", "curing_and_preparation", "preparation_method"),
        "Synergy_flag": ("Synergy flag", "协同体系标记", "formulation_loading", "synergy"),
        "Main_FR_present": ("Main FR presence", "主阻燃剂存在标记", "other", "presence_flag"),
        "Co_FR_present": ("Co-FR presence", "协同阻燃剂存在标记", "other", "presence_flag"),
    }
    if base_norm in exact_map:
        en, cn, group, key = exact_map[base_norm]
        result.update(
            parent_variable=en,
            parent_variable_cn=cn,
            parent_feature_group=group,
            mapping_type="base_or_transform",
            mechanism_key=key,
            mapping_note="Base and mathematical transforms merged into one parent variable.",
        )
        return result

    # Element-presence flags.
    m = re.match(r"^Has_([A-Za-z]+)$", base_norm)
    if m:
        element = m.group(1)
        result.update(
            parent_variable=f"Presence of {element}",
            parent_variable_cn=f"是否含{element}",
            parent_feature_group="elemental_composition",
            mapping_type="binary_flag",
            mechanism_key="element_presence",
            mapping_note="Binary presence flag; interpret together with actual elemental loading.",
        )
        return result

    # One-hot categorical variables.
    if base_norm.startswith("Synergy_type_"):
        category = base_norm.replace("Synergy_type_", "", 1)
        result.update(
            parent_variable="Synergy type",
            parent_variable_cn="协同类型",
            parent_feature_group="curing_and_preparation",
            mapping_type="one_hot_category",
            mechanism_key="synergy_type",
            mapping_note=f"One-hot category '{category}' merged under the Synergy type parent variable.",
        )
        return result

    if base_norm.startswith("Preparation_Method_"):
        category = base_norm.replace("Preparation_Method_", "", 1)
        result.update(
            parent_variable="Preparation method",
            parent_variable_cn="制备/引入方式",
            parent_feature_group="curing_and_preparation",
            mapping_type="one_hot_category",
            mechanism_key="preparation_method",
            mapping_note=f"One-hot category '{category}' merged under Preparation method.",
        )
        return result

    # Molecular descriptors by molecule scope.
    m = re.match(r"^(main|co|curing)_(.+)$", base_norm, flags=re.I)
    if m:
        scope, desc = m.groups()
        scope_en = {"main": "Main FR", "co": "Co-FR", "curing": "Curing agent"}[scope.lower()]
        scope_cn = {"main": "主阻燃剂", "co": "协同阻燃剂", "curing": "固化剂"}[scope.lower()]
        desc_en, desc_cn = _descriptor_label(desc)
        key = f"descriptor_{desc_en.lower()}"
        result.update(
            parent_variable=f"{scope_en} {desc_en}",
            parent_variable_cn=f"{scope_cn}{desc_cn}",
            parent_feature_group="molecular_descriptor",
            mapping_type="molecular_descriptor",
            mechanism_key=key,
            mapping_note="Molecular descriptor retained at scope-specific parent level.",
        )
        return result

    return result


